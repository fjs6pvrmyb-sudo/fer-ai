import { strict as assert } from "node:assert";
import { randomUUID } from "node:crypto";
import { after, describe, it } from "node:test";
import {
  accounts,
  ids,
  localClient,
  localConfig,
  signedIn,
} from "./local-demo.mjs";

const config = localConfig();
const anonymous = localClient(config.url, config.key);
const root = localClient(config.url, config.serviceKey);
const [admin, operator, coffee] = await Promise.all(
  [accounts.admin, accounts.operator, accounts.coffee].map((email) =>
    signedIn(email, config),
  ),
);
const operation = () => ({
  p_org: ids.bakery,
  p_request: randomUUID(),
  p_lines: [{ product_id: ids.bread, price_id: ids.breadPrice, quantity: 1 }],
  p_payments: [
    { method: "cash", amount_minor: "120000" },
    { method: "transfer", amount_minor: "80000" },
  ],
});
const { data: actor } = await operator.auth.getUser();
const operatorId = actor.user.id;
const createdSales = [];

function success(result) {
  assert.equal(result.error, null, result.error?.message);
  return result.data;
}

after(async () => {
  // Clean only records generated by this integration run.
  if (!createdSales.length) return;
  for (const [table, column] of [
    ["audit_events", "entity_id"],
    ["sale_requests", "sale_id"],
    ["payments", "sale_id"],
    ["sale_lines", "sale_id"],
    ["sales", "id"],
  ]) {
    success(
      await root
        .from(table)
        .delete()
        .eq("organization_id", ids.bakery)
        .in(column, createdSales),
    );
  }
});

describe("Supabase local con Auth, PostgreSQL y RLS", () => {
  it("bloquea anónimos y separa catálogos entre usuarios", async () => {
    assert.ok((await anonymous.rpc("confirm_sale", operation())).error);
    assert.ok((await anonymous.from("catalog").select("id")).error);
    const catalog = success(
      await operator.from("catalog").select("id,organization_id"),
    );
    assert.ok(catalog.some(({ id }) => id === ids.bread));
    assert.ok(
      catalog.every(({ organization_id }) => organization_id === ids.bakery),
    );
    assert.deepEqual(
      success(
        await operator
          .from("catalog")
          .select("id")
          .eq("organization_id", ids.coffee),
      ),
      [],
    );
    assert.deepEqual(
      success(await coffee.from("catalog").select("id").eq("id", ids.bread)),
      [],
    );
  });

  it("deniega escritura directa, roles insuficientes y referencias cruzadas", async () => {
    assert.ok(
      (
        await operator
          .from("products")
          .update({ name: "Prohibido" })
          .eq("id", ids.bread)
      ).error,
    );
    const edit = {
      p_org: ids.bakery,
      p_id: ids.bread,
      p_name: "Prohibido",
      p_amount: "1",
      p_active: true,
    };
    assert.equal(
      (await operator.rpc("save_product", edit)).error?.message,
      "forbidden",
    );
    assert.equal(
      (await admin.rpc("save_product", { ...edit, p_id: ids.coffeeProduct }))
        .error?.message,
      "invalid_product",
    );
    assert.equal(
      (await coffee.rpc("confirm_sale", operation())).error?.message,
      "forbidden",
    );
    const payload = operation();
    payload.p_lines = [
      { product_id: ids.coffeeProduct, price_id: ids.coffeePrice, quantity: 1 },
    ];
    assert.equal(
      (await operator.rpc("confirm_sale", payload)).error?.message,
      "catalog_changed",
    );
    const crossPrice = await root.from("product_prices").insert({
      organization_id: ids.bakery,
      product_id: ids.coffeeProduct,
      currency: "CRC",
      scale: 2,
      amount_minor: 1,
    });
    assert.equal(crossPrice.error?.code, "23503");
  });

  it("conserva precios históricos y rechaza confirmar con un precio anterior", async () => {
    const product = success(
      await admin.rpc("save_product", {
        p_org: ids.bakery,
        p_id: null,
        p_name: "Producto de prueba",
        p_amount: "500000",
        p_active: true,
      }),
    );
    try {
      const initial = success(
        await admin
          .from("catalog")
          .select("price_id")
          .eq("id", product)
          .single(),
      );
      success(
        await admin.rpc("save_product", {
          p_org: ids.bakery,
          p_id: product,
          p_name: "Producto de prueba",
          p_amount: "600000",
          p_active: true,
        }),
      );
      const history = success(
        await operator
          .from("catalog_price_history")
          .select("amount_minor,ended_at")
          .eq("product_id", product)
          .order("effective_at"),
      );
      assert.deepEqual(
        history.map(({ amount_minor }) => amount_minor),
        ["500000", "600000"],
      );
      assert.ok(history[0].ended_at);
      assert.equal(history[1].ended_at, null);
      const payload = {
        ...operation(),
        p_lines: [
          { product_id: product, price_id: initial.price_id, quantity: 1 },
        ],
      };
      assert.equal(
        (await operator.rpc("confirm_sale", payload)).error?.message,
        "catalog_changed",
      );
    } finally {
      success(
        await root
          .from("audit_events")
          .delete()
          .eq("organization_id", ids.bakery)
          .eq("entity_id", product),
      );
      success(
        await root
          .from("product_prices")
          .delete()
          .eq("organization_id", ids.bakery)
          .eq("product_id", product),
      );
      success(
        await root
          .from("products")
          .delete()
          .eq("organization_id", ids.bakery)
          .eq("id", product),
      );
    }
  });

  it("persiste una venta dividida y parcial una sola vez con reintentos concurrentes", async () => {
    const payload = operation();
    const results = await Promise.all(
      Array.from({ length: 5 }, () => operator.rpc("confirm_sale", payload)),
    );
    const sale = results.find((result) => !result.error)?.data;
    if (sale) createdSales.push(sale);
    for (const result of results) assert.equal(success(result), sale);
    assert.ok(sale);
    const row = success(
      await operator
        .from("sales_overview")
        .select("total_minor,paid_minor,balance_minor")
        .eq("id", sale)
        .single(),
    );
    assert.deepEqual(row, {
      total_minor: "500000",
      paid_minor: "200000",
      balance_minor: "300000",
    });
    assert.equal(
      success(
        await operator.from("payment_details").select("id").eq("sale_id", sale),
      ).length,
      2,
    );
    assert.equal(
      success(
        await admin
          .from("audit_events")
          .select("id")
          .eq("entity_id", sale)
          .eq("action", "sale_confirmed"),
      ).length,
      1,
    );
    assert.deepEqual(
      success(await coffee.from("sales_overview").select("id").eq("id", sale)),
      [],
    );
    assert.deepEqual(
      success(
        await coffee.from("payment_details").select("id").eq("sale_id", sale),
      ),
      [],
    );
    assert.ok(
      (await coffee.from("sales").update({ total_minor: 1 }).eq("id", sale))
        .error,
    );
    const different = { ...payload, p_payments: [] };
    assert.equal(
      (await operator.rpc("confirm_sale", different)).error?.message,
      "idempotency_conflict",
    );
  });

  it("rechaza sobrecobro y permite corregir la solicitud fallida sin dejar venta parcial", async () => {
    const payload = operation();
    const invalid = {
      ...payload,
      p_payments: [{ method: "cash", amount_minor: "500001" }],
    };
    assert.equal(
      (await operator.rpc("confirm_sale", invalid)).error?.message,
      "overpayment",
    );
    assert.deepEqual(
      success(
        await root
          .from("sale_requests")
          .select("sale_id")
          .eq("request_id", payload.p_request),
      ),
      [],
    );
    const sale = success(
      await operator.rpc("confirm_sale", { ...payload, p_payments: [] }),
    );
    createdSales.push(sale);
    assert.equal(
      success(
        await operator
          .from("sales_overview")
          .select("balance_minor")
          .eq("id", sale)
          .single(),
      ).balance_minor,
      "500000",
    );
  });

  it("respeta revocación y evita eliminar el último administrador", async () => {
    const { data } = await admin.auth.getUser();
    assert.equal(
      (
        await admin.rpc("set_membership", {
          p_org: ids.bakery,
          p_user: data.user.id,
          p_role: "manager",
          p_active: true,
        })
      ).error?.message,
      "last_admin",
    );
    const membership = {
      p_org: ids.bakery,
      p_user: operatorId,
      p_role: "operator",
    };
    try {
      success(
        await admin.rpc("set_membership", { ...membership, p_active: false }),
      );
      assert.deepEqual(
        success(await operator.from("catalog").select("id")),
        [],
      );
      assert.equal(
        (await operator.rpc("confirm_sale", operation())).error?.message,
        "forbidden",
      );
    } finally {
      success(
        await admin.rpc("set_membership", { ...membership, p_active: true }),
      );
    }
  });
});
